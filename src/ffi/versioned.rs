//! Structs that begin with `size_t struct_size` (agc_abi.h, D7). A caller
//! built against an older header passes a smaller struct: the fields it does
//! not know take their zero default. A caller built against a newer header
//! passes a larger one: the tail this library does not know is ignored.
//!
//! So a caller's struct is never used in place. `read` copies the prefix both
//! sides know into a zeroed value of the type this library was compiled
//! against; `write_back` copies results into that same prefix only.

use std::mem::MaybeUninit;
use std::ptr;

use crate::bindings::*;
use crate::ffi::error::FfiError;

/// A header struct whose first field is `struct_size: usize`.
///
/// # Safety
/// Implement only for structs made of integers, raw pointers, and arrays,
/// unions and structs of those: types for which every bit pattern, including
/// all zeros, is a valid value. No references, `bool`, Rust enums or `NonNull`.
/// The headers contain no C `bool`, and bindgen turns C enums into integer
/// constants, so the generated structs qualify.
pub unsafe trait CStruct: Copy {}

macro_rules! c_structs {
    ($($t:ty),* $(,)?) => {
        // SAFETY: generated by bindgen from the headers; the fields are
        // integers, raw pointers, and aggregates of those (see CStruct).
        $(unsafe impl CStruct for $t {})*
    };
}

c_structs!(
    agc_ctx_config,
    agc_error_detail,
    agc_create_key_params,
    agc_provider_requirements,
    agc_key_info_response,
    agc_list_keys_params,
    agc_transform_key_params,
    agc_create_policy_request,
    agc_update_policy_request,
    agc_read_policy_response,
    agc_list_policies_request,
    agc_policy_summary_response,
);

const SIZE_FIELD: usize = size_of::<usize>();

/// Copies the caller's `*p` into a value of the current layout.
///
/// Fails with `InvalidArgument` if `p` is NULL or `struct_size` is 0 (the
/// caller forgot `AGC_INIT`), and with `AbiMismatch` if `struct_size` cannot
/// even hold the `struct_size` field.
///
/// # Safety
/// `p` is NULL or aligned for `T`, with at least `struct_size` readable bytes
/// that no one writes during the call.
pub unsafe fn read<T: CStruct>(p: *const T, what: &'static str) -> Result<T, FfiError> {
    if p.is_null() {
        return Err(FfiError::invalid(format!("{what} must not be NULL")));
    }
    // SAFETY: p is non-null and aligned for T, whose first field is a usize at offset 0.
    let caller_size = unsafe { p.cast::<usize>().read() };
    if caller_size == 0 {
        return Err(FfiError::invalid(format!("{what}.struct_size is 0 (missing AGC_INIT?)")));
    }
    if caller_size < SIZE_FIELD {
        return Err(FfiError::AbiMismatch(what));
    }
    let n = caller_size.min(size_of::<T>());
    let mut v = MaybeUninit::<T>::zeroed();
    // SAFETY: the caller guarantees `caller_size >= n` readable bytes at p; v has
    // size_of::<T>() >= n bytes; the regions are distinct.
    unsafe { ptr::copy_nonoverlapping(p.cast::<u8>(), v.as_mut_ptr().cast::<u8>(), n) };
    // SAFETY: every byte is initialised (zeroed, then partly overwritten), and
    // any bit pattern is a valid T (CStruct).
    let mut v = unsafe { v.assume_init() };
    // From here on the value describes this library's layout.
    // SAFETY: v is a T, whose first field is the usize struct_size.
    unsafe { ptr::from_mut(&mut v).cast::<usize>().write(size_of::<T>()) };
    Ok(v)
}

/// Copies `v` back into the part of the caller's struct the caller knows,
/// leaving its `struct_size` unchanged.
///
/// # Safety
/// `p` is non-NULL, aligned for `T`, with `struct_size >= size_of::<usize>()`
/// writable bytes (as checked by a preceding `read` of the same pointer).
pub unsafe fn write_back<T: CStruct>(p: *mut T, v: &T) {
    // SAFETY: as above, the first field is the caller's struct_size.
    let caller_size = unsafe { p.cast::<usize>().read() };
    let n = caller_size.min(size_of::<T>());
    if n <= SIZE_FIELD {
        return;
    }
    // SAFETY: bytes SIZE_FIELD..n are within both the caller's struct (caller
    // contract) and v. Copying padding bytes this way is an untyped copy.
    unsafe {
        ptr::copy_nonoverlapping(
            ptr::from_ref(v).cast::<u8>().add(SIZE_FIELD),
            p.cast::<u8>().add(SIZE_FIELD),
            n - SIZE_FIELD,
        )
    };
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A stand-in for "version 2 of a struct": same prefix as v1, one more field.
    #[repr(C)]
    #[derive(Clone, Copy, Debug, PartialEq)]
    struct V2 {
        struct_size: usize,
        a: u32,
        b: u64,
    }
    // SAFETY: integers only.
    unsafe impl CStruct for V2 {}

    #[repr(C)]
    #[derive(Clone, Copy)]
    struct V1 {
        struct_size: usize,
        a: u32,
    }

    #[repr(C)]
    #[derive(Clone, Copy)]
    struct V3 {
        struct_size: usize,
        a: u32,
        b: u64,
        c: u64,
    }

    /// `read` from a caller struct of another version. The test structs share
    /// alignment, and each reference covers its own struct_size bytes.
    fn read_from<C>(caller: &C) -> Result<V2, FfiError> {
        // SAFETY: as above.
        unsafe { read(ptr::from_ref(caller).cast::<V2>(), "v") }
    }

    #[test]
    fn same_version_is_copied() {
        let caller = V2 { struct_size: size_of::<V2>(), a: 1, b: 2 };
        let v = read_from(&caller).unwrap();
        assert_eq!(v, caller);
    }

    #[test]
    fn older_caller_gets_zero_defaults_for_the_tail() {
        let caller = V1 { struct_size: size_of::<V1>(), a: 7 };
        let v = read_from(&caller).unwrap();
        assert_eq!(v, V2 { struct_size: size_of::<V2>(), a: 7, b: 0 });
    }

    #[test]
    fn newer_caller_tail_is_ignored() {
        let caller = V3 { struct_size: size_of::<V3>(), a: 1, b: 2, c: 3 };
        let v = read_from(&caller).unwrap();
        assert_eq!(v, V2 { struct_size: size_of::<V2>(), a: 1, b: 2 });
    }

    #[test]
    fn null_and_missing_init_are_invalid_arguments() {
        // SAFETY: NULL is allowed.
        let null = unsafe { read::<V2>(ptr::null(), "v") };
        assert!(matches!(null, Err(FfiError::InvalidArgument(_))));
        let zero = V2 { struct_size: 0, a: 1, b: 2 };
        assert!(matches!(read_from(&zero), Err(FfiError::InvalidArgument(_))));
    }

    #[test]
    fn size_smaller_than_the_size_field_is_abi_mismatch() {
        let tiny = V2 { struct_size: 3, a: 1, b: 2 };
        assert!(matches!(read_from(&tiny), Err(FfiError::AbiMismatch("v"))));
    }

    #[test]
    fn write_back_touches_only_what_the_older_caller_has() {
        // An older caller's struct, followed by memory that is not theirs.
        #[repr(C)]
        struct Frame {
            v1: V1,
            after: [u8; 16],
        }
        let mut frame = Frame { v1: V1 { struct_size: size_of::<V1>(), a: 0 }, after: [0xAA; 16] };
        let result = V2 { struct_size: size_of::<V2>(), a: 9, b: u64::MAX };

        // SAFETY: frame.v1 is aligned like V2 and its struct_size covers it.
        unsafe { write_back(ptr::from_mut(&mut frame.v1).cast::<V2>(), &result) };

        assert_eq!(frame.v1.a, 9);
        assert_eq!(frame.v1.struct_size, size_of::<V1>(), "struct_size stays the caller's");
        assert!(frame.after.iter().all(|&b| b == 0xAA), "nothing written past the caller's struct");
    }
}
